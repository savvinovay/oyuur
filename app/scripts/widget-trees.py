# Tree pictures for the Android widgets (OYUUR-39, design/oyuur-37/спец.md, 8 and Т6).
# Source: the snapshots of the app's own tree drawings in design/oyuur-37/img/trees/
# ({skin}-{stage}-{d|n}[-thirsty].png, PNG-8, feet at the bottom edge).
# Out: app/assets/widget/trees/{skin}_{stage}_{d|n}[_t].png (172 files) and src/widget/trees.gen.ts
# (static requires for Metro + the size of each picture).
# - 7 kinds × 6 stages × day/night × calm/thirsty = 168, plus the dead tree 2 × day/night = 4 (one drawing for all kinds).
# - The thirsty maple is its calm drawing muted (saturation 0.62, brightness +6 % day / +2 % night): in the app a thirsty
#   maple turns brown like a dead one (спец 8, "временно").
# Run from app/: python scripts/widget-trees.py
import json
import os
import shutil

from PIL import Image, ImageEnhance

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
SRC = os.path.join(APP, '..', 'design', 'oyuur-37', 'img', 'trees')
OUT = os.path.join(APP, 'assets', 'widget', 'trees')
GEN = os.path.join(APP, 'src', 'widget', 'trees.gen.ts')

SKINS = ['oak', 'sakura', 'spruce', 'birch', 'maple', 'apple', 'palm']
STAGES = ['sprout', 'seedling', 'bush', 'young', 'tree', 'grand']


def muted(path, night):
    img = Image.open(path).convert('RGBA')
    alpha = img.getchannel('A')
    rgb = ImageEnhance.Color(img.convert('RGB')).enhance(0.62)
    rgb = ImageEnhance.Brightness(rgb).enhance(1.02 if night else 1.06)
    out = rgb.convert('RGBA')
    out.putalpha(alpha)
    return out


def save8(img, path):
    # PNG-8 with alpha, like the source files.
    img.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(path, optimize=True)


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    sizes = {}

    def put(key, src_name, make=None):
        dst = os.path.join(OUT, key + '.png')
        src = os.path.join(SRC, src_name + '.png')
        if make:
            save8(make(src), dst)
        else:
            shutil.copyfile(src, dst)
        with Image.open(dst) as im:
            sizes[key] = im.size

    for skin in SKINS:
        for stage in STAGES:
            for dn in ['d', 'n']:
                put(f'{skin}_{stage}_{dn}', f'{skin}-{stage}-{dn}')
                if skin == 'maple':
                    put(f'{skin}_{stage}_{dn}_t', f'{skin}-{stage}-{dn}', lambda p, n=(dn == 'n'): muted(p, n))
                else:
                    put(f'{skin}_{stage}_{dn}_t', f'{skin}-{stage}-{dn}-thirsty')
    for stage in ['dead', 'deadsmall']:
        for dn in ['d', 'n']:
            put(f'{stage}_{dn}', f'oak-{stage}-{dn}')

    keys = sorted(sizes)
    lines = [
        '// Generated by scripts/widget-trees.py — do not edit by hand.',
        '// Tree pictures of the Android widgets: a static require for each (Metro needs them) and its size in px.',
        '/* eslint-disable */',
        'export const TREE_PICS: Record<string, { src: number; w: number; h: number }> = {',
    ]
    for k in keys:
        w, h = sizes[k]
        lines.append(f"  {k}: {{ src: require('../../assets/widget/trees/{k}.png'), w: {w}, h: {h} }},")
    lines.append('};')
    with open(GEN, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    total = sum(os.path.getsize(os.path.join(OUT, k + '.png')) for k in keys)
    print(f'{len(keys)} pictures, {total / 1024:.0f} KB')


if __name__ == '__main__':
    main()

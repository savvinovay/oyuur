export type Lang = 'en' | 'ru';
export type LangSetting = Lang | 'auto';
export const dictionaries: Record<Lang, Dict> = { en, ru };

export function deviceLang(): Lang {
  const code = getLocales()[0]?.languageCode;
  return code === 'ru' ? 'ru' : 'en';
}

type StringKey = { [K in keyof Dict]: Dict[K] extends string ? K : never }[keyof Dict];

export function makeT(lang: Lang) {
  const dict = dictionaries[lang];
  const t = (key: StringKey, vars?: Record<string, string | number>) =>
    (dict[key] as string).replace(/\{(\w+)\}/g, (_, v) => String(vars?.[v] ?? ''));
  return Object.assign(t, { dict, lang });
}

export type T = ReturnType<typeof makeT>;

/** Which of three word forms goes with n: 1 день, 2 дня, 5 дней; 1 day, 2 days. */
export function pluralForm(lang: Lang, n: number): 0 | 1 | 2 {
  const abs = Math.abs(n);
  if (lang === 'en') return abs === 1 ? 0 : 2;
  const ten = abs % 10;
  const hundred = abs % 100;
  if (ten === 1 && hundred !== 11) return 0;
  if (ten >= 2 && ten <= 4 && (hundred < 12 || hundred > 14)) return 1;
  return 2;
}

/** "21 день роста" / "21 days of growth". */
export const stageDaysText = (t: T, n: number) => t('stageDays', { n, word: t.dict.stageDayWords[pluralForm(t.lang, n)] });

/** Acorns with their thousands grouped (wave 5 spec 1.3): RU "1 240" (a narrow no-break space), EN "1,240". */
export function formatAcorns(n: number, lang: Lang): string {
  const digits = String(Math.abs(Math.round(n))).replace(/\B(?=(\d{3})+(?!\d))/g, lang === 'ru' ? ' ' : ',');
  return n < 0 ? `-${digits}` : digits;
}

/** "15 желудей" / "15 acorns". */
export const acornsText = (t: T, n: number) =>
  t('acornsCount', { n: formatAcorns(n, t.lang), word: t.dict.acornWords[pluralForm(t.lang, n)] });
